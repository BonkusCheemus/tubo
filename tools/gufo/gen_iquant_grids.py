#!/usr/bin/env python3
"""Regenerates src/core/quant/iquant_grids.inc from llama.cpp ggml-common.h.

Usage: gen_iquant_grids.py <ggml-common.h> <out.inc>

The tables are copied verbatim (MIT, llama.cpp / ggml-org). The .inc is
included twice, once for the host (ggml_dequant.cpp) and once for the device
(hip/quant_ops.hpp); each includer defines GUFO_IQ_TABLE(type, name, size).
"""
import re
import sys

WANT = [  # (ggml name, C type, gufo name)
    ("ksigns_iq2xs", "std::uint8_t", "KsignsIq2xs"),
    ("iq2xxs_grid", "std::uint64_t", "Iq2xxsGrid"),
    ("iq2xs_grid", "std::uint64_t", "Iq2xsGrid"),
    ("iq2s_grid", "std::uint64_t", "Iq2sGrid"),
    ("iq3xxs_grid", "std::uint32_t", "Iq3xxsGrid"),
    ("iq1s_grid", "std::uint64_t", "Iq1sGrid"),
]


def main(src, dst):
    text = open(src).read()
    out = ["// GENERATED by tools/gufo/gen_iquant_grids.py from llama.cpp",
           "// ggml/src/ggml-common.h (MIT). Do not edit by hand.",
           "// Includer defines GUFO_IQ_TABLE(type, name, size).", ""]
    for gname, ctype, name in WANT:
        m = re.search(r"GGML_TABLE_BEGIN\((\w+),\s*%s,\s*(\w+)\)(.*?)GGML_TABLE_END\(\)"
                      % gname, text, re.S)
        size = {"NGRID_IQ1S": 2048}.get(m.group(2)) or int(m.group(2))
        vals = [v for v in re.split(r"[\s,]+", m.group(3).strip()) if v]
        assert len(vals) == size, (gname, len(vals), size)
        suffix = "ULL" if "64" in ctype else ("U" if "uint32" in ctype else "")
        body = []
        for i in range(0, len(vals), 4):
            body.append("    " + ", ".join(v + suffix for v in vals[i:i + 4]) + ",")
        out.append("GUFO_IQ_TABLE(%s, %s, %d) = {" % (ctype, name, size))
        out += body
        out.append("};")
        out.append("")
    open(dst, "w").write("\n".join(out))


main(sys.argv[1], sys.argv[2])
